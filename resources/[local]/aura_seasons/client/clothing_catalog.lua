-- Componente 1 (Máscara) y Prop 0 (Sombreros/Cascos) (Max 12.0)
function ClothingCatalog.GetHeadScore(maskDrawable, hatProp, isMale)
    local score = 0.0
    if maskDrawable > 0 and maskDrawable ~= 15 and maskDrawable ~= -1 then
        local maskScore = ClothingCatalog.Masks[maskDrawable]
        score = score + (maskScore or 4.0)
    end
    if hatProp ~= -1 and hatProp ~= 255 then
        local hatTable = isMale and ClothingCatalog.MaleHats or ClothingCatalog.FemaleHats
        local hatScore = hatTable[hatProp]
        score = score + (hatScore or 4.0)
    end
    return math.min(12.0, score)
end
